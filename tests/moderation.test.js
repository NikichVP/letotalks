const test = require('node:test');
const assert = require('node:assert/strict');
const { hasBadWords } = require('../comment_moderation');
const shared = require('../public/profanity');

// Невинные слова и фразы — НЕ должны срабатывать: за мат сервер отклоняет отзыв
// и засчитывает нарушение (раньше — сразу вечный бан).
const CLEAN = [
  'требовать', 'хлеб', 'себе', 'сукно', 'искусство', 'небо', 'потребность',
  'благодарю', 'блаженство', 'требования к учителю', 'хлебобулочные изделия',
  'Очень требовательный преподаватель, но справедливый',
  'Любит давать сложные задачи, требует дисциплины',
  'серебро', 'погреб', 'требуха', 'улыбается',
  // Реальные ложные срабатывания прошлых версий фильтра:
  'Отлично объясняет колебания', 'Я долго колебался', 'Небанальные задачи',
  'Учитель сказал: 3 балла', 'Кабинет 364 на втором этаже', 'Сукачева лучшая',
  'Физрук водит в зал, упражнения интересные', 'Объясняет тебе всё понятно',
  'Он не будет ругать', 'Ребята его любят', 'Небольшие домашки', 'Глеб Иванович',
  'учебник', 'учеба', 'мудрый учитель', 'вебинар', 'он подстрахует на контрольной',
  'чмокнул', 'бляха-муха', 'Пешка на e6', 'учится в 5Б', 'Хуан', 'хуже некуда',
  'перебор с домашкой', 'поедем на экскурсию', 'застрахуем', 'колеблется', 'гребля',
  'e-mail: ivanov@student.letovo.ru', 'Задаёт по 10-15 задач'
];

// Настоящий мат — должен ловиться (в т.ч. с обфускацией).
const PROFANE = [
  'ты хуй', 'блядь', 'сука', 'сукин сын', 'еблан', 'пиздец', 'нахуй',
  'мразь', 'гандон', 'долбоёб', 'х у й', 'хуйня', 'сукааа', 'бляяя',
  'что за пидор', 'залупа', 'xуй', 'пи3дец', 'заебал', 'уёбище', 'мудак',
  'он чмо', 'бл@дь', 'бл9ть', '6ля', 'ебать', 'ёбаный', 'х у й н я', 'ХУЙ'
];

test('profanity filter: clean words are not flagged', () => {
  for (const phrase of CLEAN) {
    assert.equal(hasBadWords(phrase), false, `ложное срабатывание на: "${phrase}"`);
  }
});

test('profanity filter: real profanity is flagged', () => {
  for (const phrase of PROFANE) {
    assert.equal(hasBadWords(phrase), true, `пропущен мат: "${phrase}"`);
  }
});

test('profanity filter: server and browser use the same implementation', () => {
  for (const phrase of [...CLEAN, ...PROFANE]) {
    assert.equal(shared.hasBadWords(phrase), hasBadWords(phrase), phrase);
  }
});
